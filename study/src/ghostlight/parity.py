"""Deterministic cross-implementation parity vectors for the centroid equation."""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

import numpy as np

from ghostlight.config import TruthConfig
from ghostlight.physics import (
    astrometric_baseline_mas,
    baseline_relative_centroid_mas,
    dark_centroid_shift_mas,
    direct_flux_weighted_difference_mas,
    lens_trajectory,
    magnification,
)

PARITY_TIMES_DAYS = (-1095.75, -276.0, 0.0, 276.0, 1095.75)
PARITY_CASES = (
    ("primary", 0.3, 20.0, 67.0),
    ("zero_blend_flux", 0.0, 20.0, 137.0),
    ("zero_blend_offset", 1.0, 0.0, 0.0),
    ("maximum_blend_primary_orientation", 1.0, 20.0, 67.0),
    ("maximum_blend_rotated_orientation", 1.0, 20.0, 157.0),
)


def canonical_parity_fixture() -> dict[str, Any]:
    """Return deterministic known-truth vectors without constructing an RNG."""

    truth = TruthConfig()
    truth.validate()
    times = np.asarray(PARITY_TIMES_DAYS, dtype=float) + truth.t_0_days
    u_vectors = lens_trajectory(times, truth)
    source_positions = astrometric_baseline_mas(times, truth)
    dark_shift = dark_centroid_shift_mas(u_vectors, truth.theta_e_mas)
    cases = []
    for name, flux_ratio, offset_mas, orientation_deg in PARITY_CASES:
        angle = np.deg2rad(orientation_deg)
        offset = offset_mas * np.array([np.cos(angle), np.sin(angle)])
        reduced = baseline_relative_centroid_mas(
            u_vectors,
            truth.theta_e_mas,
            flux_ratio,
            offset,
        )
        direct = direct_flux_weighted_difference_mas(
            source_positions,
            u_vectors,
            truth.theta_e_mas,
            flux_ratio,
            offset,
        )
        cases.append(
            {
                "name": name,
                "blend_flux_ratio": flux_ratio,
                "blend_offset_magnitude_mas": offset_mas,
                "blend_orientation_deg": orientation_deg,
                "blend_offset_xy_mas": offset.tolist(),
                "baseline_relative_centroid_xy_mas": reduced.tolist(),
                "direct_flux_weighted_difference_xy_mas": direct.tolist(),
            }
        )
    return {
        "schema_version": "1.0",
        "purpose": (
            "Cross-implementation parity fixture generated by canonical Ghostlight Python; "
            "no random generator is constructed."
        ),
        "units": {
            "times_days": "days relative to t0=0",
            "angles": "degrees",
            "astrometry": "milliarcseconds",
            "u_vectors": "dimensionless",
        },
        "truth": {
            "theta_e_mas": truth.theta_e_mas,
            "t_0_days": truth.t_0_days,
            "t_e_days": truth.t_e_days,
            "u_0": truth.u_0,
            "trajectory_angle_deg": truth.trajectory_angle_deg,
        },
        "times_days": times.tolist(),
        "u_vectors": u_vectors.tolist(),
        "magnifications": magnification(np.linalg.norm(u_vectors, axis=1)).tolist(),
        "dark_centroid_shift_xy_mas": dark_shift.tolist(),
        "cases": cases,
    }


def write_parity_fixture(path: Path) -> None:
    path.write_text(
        json.dumps(canonical_parity_fixture(), indent=2, sort_keys=True, allow_nan=False) + "\n"
    )


def main() -> None:
    parser = argparse.ArgumentParser(description="Write deterministic Ghostlight parity vectors")
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    write_parity_fixture(args.output)


if __name__ == "__main__":
    main()
